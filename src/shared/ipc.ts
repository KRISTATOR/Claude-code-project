import { z } from 'zod';
import { connectionConfigSchema } from '@core/connection';

export { IPC } from './channels';

/** Input schemas for IPC channels, validated in main (CLAUDE.md, Electron conventions). */
export const configSetInput = connectionConfigSchema;

export const openExternalInput = z
  .url()
  .refine((value) => new URL(value).protocol === 'https:', { message: 'https-only' });

/** Keys the renderer may keep in encrypted storage (Supabase session, last user). */
export const secureKeyInput = z.string().regex(/^[a-z0-9][a-z0-9._-]{0,80}$/i);
export const secureValueInput = z.string().max(256 * 1024);

/** No path separators, reserved characters or control characters. */
export function isSafeFileName(name: string): boolean {
  if (/[\\/:*?"<>|]/.test(name)) return false;
  for (let index = 0; index < name.length; index += 1) {
    if (name.charCodeAt(index) < 32) return false;
  }
  return true;
}

export const MAX_SAVE_BYTES = 500 * 1024 * 1024;

export const saveFileInput = z.object({
  defaultName: z.string().min(1).max(200).refine(isSafeFileName, { message: 'invalid-name' }),
  filters: z
    .array(
      z.object({
        name: z.string().max(80),
        extensions: z.array(z.string().regex(/^[a-z0-9]{1,8}$/)).max(5),
      }),
    )
    .max(5),
  data: z.instanceof(Uint8Array).refine((bytes) => bytes.byteLength <= MAX_SAVE_BYTES, {
    message: 'too-large',
  }),
});

/** Invite codes as generated by create_invite(): e.g. "LIPNO-7K3Q". */
export const inviteCodePattern = /^[A-Z2-9]{5}-[A-Z2-9]{4}$/;

export function parseInviteLink(url: string): string | null {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== 'zazemi:') return null;
    const path = `${parsed.hostname}${parsed.pathname}`.replace(/\/+$/, '');
    const match = /^pozvanka\/([A-Za-z2-9]{5}-[A-Za-z2-9]{4})$/.exec(path);
    const code = match?.[1]?.toUpperCase() ?? null;
    return code && inviteCodePattern.test(code) ? code : null;
  } catch {
    return null;
  }
}
